# src/config.py
"""Все параметры и допущения решения в одном месте.

Условия правил R01–R12 сверены с приказом Банка России от 05.11.2025 № ОД-2506
(текст скачан с cbr.ru/Crosscut/LawActs/File/10123) и FAQ ЦБ по 161-ФЗ.
Правила сервиса «Защита близких» сверены со страницей vtb.ru (FAQ сервиса).
Экономические и поведенческие параметры — допущения команды; у каждого — обоснование.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class RulesConfig:
    """Пороги правил ОД-2506. Источник: приказ ЦБ № ОД-2506 (сверено с первоисточником)."""

    phone_change_hours: int = 48          # R09: смена номера в ДБО/на Госуслугах за 48 ч до перевода (п. 1.10)
    third_party_signal_hours: int = 6     # R06: сигнал сторонних организаций выявлен ≥6 ч до перевода (п. 1.9)
    r11_self_transfer_min: float = 200_000     # R11: предшествующий перевод себе через СБП > 200 тыс. ₽ (п. 1.12)
    r11_interval_hours: int = 24               # R11: интервал < 24 ч (п. 1.12)
    r11_no_relation_months: int = 6            # R11: получателю не переводили 6 мес (п. 1.12)
    r12_crossborder_min: float = 100_000       # R12: трансграничный перевод получателя > 100 тыс. ₽ за 24 ч (п. 1.11)
    r12_interval_hours: int = 24               # R12: окно 24 ч (п. 1.11)
    suspension_days: int = 2              # приостановка перевода, 161-ФЗ ч. 3.10 ст. 8 (в ред. 369-ФЗ)
    confirm_deadline_days: int = 1        # клиент может подтвердить не позднее 1 дня после приостановки
    monthly_limit_client_in_cbr_db: float = 100_000  # лимит переводов физлицам/мес, если клиент в базе ЦБ (ч. 11.6 ст. 9)
    atm_cash_limit: float = 50_000        # лимит снятия в банкомате при признаке мошеннической выдачи
    atm_cash_limit_hours: int = 48        # действие лимита на снятие наличных


@dataclass(frozen=True)
class DataConfig:
    """Параметры синтетического датасета."""

    seed: int = 42                 # фиксированный seed: все числа отчёта воспроизводятся одним запуском
    n_transactions: int = 60_000   # ≥ 50 000 по ТЗ; хватает для устойчивых метрик при fraud_rate 0,7%
    fraud_rate: float = 0.007      # доля мошеннических операций. Допущение: реальная доля ОБДС ниже,
                                   # выборка сознательно обогащена для устойчивости метрик (оговорено в отчёте)
    share_sbp: float = 0.55        # доля СБП в выборке. Обоснование: СБП+счета ≈ 75% объёма хищений (обзор ЦБ II кв. 2026)
    share_55plus: float = 0.25     # доля операций клиентов 55+. Допущение (в кейсе данных нет)
    fraud_share_55plus: float = 0.45  # доля фрода, приходящегося на 55+. Допущение: качественно следует из кейса
                                      # (история бабушки Никиты), точная статистика не публикуется
    scenario_social: float = 0.70  # соц. инженерия среди фрода. Обоснование: 28 678 из ~29,4 тыс. атак II кв. 2026 — ЦБ
    scenario_phishing: float = 0.20
    scenario_malware: float = 0.10
    risky_legit_share: float = 0.03  # доля легитимных операций, выглядящих рискованно (как покупка велосипеда
                                     # у Никиты). Допущение команды — источник ложных срабатываний
    data_lag_share: float = 0.15   # доля операций, по которым часть данных приходит с задержкой до суток
                                   # (ограничение из кейса). Допущение по частоте


@dataclass(frozen=True)
class ScoringConfig:
    """ML-скоринг и пороги решений. Применяется ТОЛЬКО к операциям без сработавших R01–R12."""

    test_size_time_split: float = 0.3   # хвост по времени — тест (без перемешивания, ближе к боевому сценарию)
    threshold_medium: float = 0.30      # risk_score ≥ 0.30 → мягкое трение (биометрия + предупреждение)
    threshold_high: float = 0.70        # risk_score ≥ 0.70 → повышенная проверка (оператор + «защитник»)
    data_lag_shift: float = 0.10        # data_lag: скор сдвигается на +0.10 к следующей ступени осторожности
    confirm_legit_soft: float = 0.85    # конверсия подтверждения легитимной операции при мягком трении
                                        # с понятным текстом. Допущение (ключевая чувствительность модели)
    confirm_legit_baseline: float = 0.55  # конверсия в baseline: жёсткая остановка без объяснения →
                                          # часть клиентов бросает платёж. Допущение
    confirm_fraud_soft: float = 0.25    # доля жертв соц. инженерии, которые всё равно подтверждают после
                                        # предупреждения (кейс: под давлением мошенника человек настаивает)
    guardian_coverage: float = 0.05     # доля клиентов с включённой «Защитой близких». Допущение
                                        # (публичной статистики проникновения сервиса нет)
    guardian_timeout_hours: int = 12    # нет решения «защитника» 12 ч → отклонение (FAQ ВТБ, сверено)
    guardian_disable_hours: int = 24    # период охлаждения на отключение защиты (кейс + FAQ ВТБ)


@dataclass(frozen=True)
class EconomicsConfig:
    """Экономика: затраты, эффект, допущения. Все суммы — рубли, если не сказано иначе."""

    budget_cap: float = 50_000_000      # ограничение кейса
    implementation_months: int = 6      # ограничение кейса
    vtb_share_obds: float = 0.12        # доля ВТБ в ОБДС физлиц. Допущение (консервативно: >30,3 млн
                                        # клиентов, но доля в хищениях не публикуется)
    support_call_cost: float = 350      # обработка обращения в поддержку. Допущение (среднерыночная оценка)
    manual_review_cost: float = 1_500   # доп. разбор антифрод-оператором. Допущение (20–30 мин работы)
    p2p_fee_rate: float = 0.003         # недополученный комиссионный доход при отказе от операции,
                                        # доля от суммы. Допущение (большинство P2P бесплатны, доход — межбанк/вывод)
    nps_gain_per_avoided_fp: float = 0.005   # +п.п. NPS за каждое избежанное ошибочное ограничение.
                                             # Допущение (слабо обосновано, в отчёте — диапазон)
    nps_gain_per_prevented_fraud: float = 0.002  # +п.п. NPS за предотвращённое хищение у клиента. Допущение
    discount_rate: float = 0.16         # ставка дисконтирования NPV, годовых. Допущение (~ключевая ставка + премия)
    horizon_years: int = 3              # горизонт NPV
    # Затраты по статьям, итого = budget_cap. Структура — допущение команды по типовому проекту внедрения.
    costs: dict[str, float] = field(default_factory=lambda: {
        "Команда (разработка, DS, аналитика)": 24_000_000,
        "Инфраструктура и лицензии": 9_000_000,
        "Интеграция с ДБО и антифрод-шиной": 8_000_000,
        "Пилот и теневой режим (shadow mode)": 4_000_000,
        "Обучение операторов и поддержки": 2_000_000,
        "Поддержка и доработки (6 мес)": 3_000_000,
    })
    # Сценарные множители эффекта (пессимистичный/базовый/оптимистичный)
    scenario_multipliers: dict[str, float] = field(default_factory=lambda: {
        "Пессимистичный": 0.6, "Базовый": 1.0, "Оптимистичный": 1.4,
    })


@dataclass(frozen=True)
class Config:
    rules: RulesConfig = field(default_factory=RulesConfig)
    data: DataConfig = field(default_factory=DataConfig)
    scoring: ScoringConfig = field(default_factory=ScoringConfig)
    economics: EconomicsConfig = field(default_factory=EconomicsConfig)


CONFIG = Config()
